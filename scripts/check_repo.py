"""Offline repository checks for os-optics-kit.

python scripts/check_repo.py [--root DIR]

Checks every tracked or new (not ignored) file:
  links       relative links and images in Markdown resolve inside the repository
  size        no file over 1 MiB; images at most 400 KiB
  forbidden   no run outputs, 3D scenes, wheels, keys or catalog releases
  paths       no absolute paths of a particular machine (home directories, drive-letter work folders)
  secrets     no access tokens or private keys
  json        every JSON file parses
  baseline    baseline.json matches pyproject.toml and tools/os_optics_kit/_version.py
  pins        exact os-optics / os-optics-kit pins in documents equal the baseline; no retired host or name
  pairs       English and Simplified Chinese documents come in pairs (README.md / README.zh-CN.md, docs/en / docs/zh-CN)

Prints one compact JSON document; exit 0 when there is no problem, 1 otherwise.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
from urllib.parse import unquote

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - Python < 3.11 is not supported by the kit
    tomllib = None  # type: ignore[assignment]

ROOT = Path(__file__).resolve().parents[1]
MAX_FILE_BYTES = 1024 * 1024
MAX_IMAGE_BYTES = 400 * 1024
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".bmp"}
SKIPPED_DIRS = {".git", ".venv", "venv", "__pycache__", "node_modules", "dist", "build", ".pytest_cache",
                ".ruff_cache", ".mypy_cache", ".tox"}

# Files that are generated by a run or must never be published.
FORBIDDEN_NAMES = {"simulation_result.json", "engine_request.json", "local_validation.json", "ray_data.json",
                   "optical_scene.json", ".env", ".pypirc"}
FORBIDDEN_SUFFIXES = {".glb", ".gltf", ".whl", ".pem", ".key", ".p12", ".pfx", ".pyc"}
FORBIDDEN_PATTERN = re.compile(r"public_optical_catalog", re.I)

MACHINE_PATHS = (
    re.compile(r"(?<![\w])[A-Za-z]:(?:\\\\?|/)(?:Users|Documents and Settings|working|cache|apps|data|tmp|temp)"
               r"(?:\\\\?|/)[\w .-]", re.I),
    re.compile(r"(?<![\w.~-])/(?:home|Users)/[A-Za-z0-9_][\w.-]*/"),
    re.compile(r"(?<![\w.~-])/[c-z]/(?:Users|working|cache|apps|data)/", re.I),
)
SECRETS = (
    ("private key", re.compile(r"-----BEGIN (?:[A-Z]+ )*PRIVATE KEY-----")),
    ("PyPI token", re.compile(r"pypi-AgE[A-Za-z0-9_-]{50,}")),
    ("GitHub token", re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{50,})")),
    ("AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("Slack token", re.compile(r"\bxox[abposr]-[A-Za-z0-9-]{10,}")),
    ("API key", re.compile(r"\b(?:sk-ant-[A-Za-z0-9_-]{20,}|sk-[A-Za-z0-9]{32,}|AIza[0-9A-Za-z_-]{35})")),
    ("OpenSci account token", re.compile(r"\boat_[A-Za-z0-9_-]{32,}")),
)
# The website's former host and the engine's former distribution name.
RETIRED_HOSTS = ("opensci-" + "optic.com",)
RETIRED_NAMES = ("opensci-" + "engine",)
VERSION = r"(\d+(?:\.\d+)+(?:(?:a|b|rc)\d+|\.post\d+|\.dev\d+)?)(?![\w+]|\.\d)"
ENGINE_PIN = re.compile(r"(?<![\w-])os-optics(?:\[[\w,\s-]+\])?==" + VERSION)
KIT_PIN = re.compile(r"(?<![\w-])os-optics-kit(?:\[[\w,\s-]+\])?==" + VERSION)
RETIRED_PIN = re.compile(r"(?<![\w-])(?:" + "|".join(map(re.escape, RETIRED_NAMES)) + r")(?:\[[\w,\s-]+\])?==")
# Install pins are checked everywhere except here: tests and these scripts use made-up versions on purpose.
PIN_EXEMPT = ("tests/", "scripts/")

LINK = re.compile(r"!?\[(?:[^\[\]]|\[[^\]]*\])*\]\(\s*<?([^)\s>]+)>?(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)")
REFERENCE = re.compile(r"^\s{0,3}\[[^\]]+\]:\s*<?(\S+?)>?(?:\s+.*)?$", re.M)
HTML_LINK = re.compile(r"<(?:a|img|source)\b[^>]*?\b(?:href|src)\s*=\s*[\"']([^\"']+)[\"']", re.I)
FENCE = re.compile(r"^ {0,3}(```|~~~)[^\n]*\n.*?^ {0,3}\1[^\n]*$", re.M | re.S)
INLINE_CODE = re.compile(r"(`+)(?:(?!\1).)+?\1", re.S)
SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")


class Problems:
    def __init__(self):
        self.items: list[dict] = []

    def add(self, check, path, message, line=None):
        self.items.append({"check": check, "path": path, "line": line, "message": message})


def repository_files(root: Path) -> list[str]:
    """Tracked and new (not ignored) files; a plain directory walk outside Git."""
    if (root / ".git").exists():
        try:
            output = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--cached", "--others",
                                     "--exclude-standard"], capture_output=True, check=True).stdout
            names = sorted({name for name in output.decode("utf-8").split("\0") if name})
            return [name for name in names if (root / name).is_file() and not _skipped(name)]
        except (OSError, subprocess.CalledProcessError):
            pass
    names = []
    for directory, folders, files in os.walk(root):
        top = Path(directory) == root
        # Top-level run*/ directories are local outputs (ignored by Git); inside a case they are reported.
        folders[:] = sorted(folder for folder in folders if folder not in SKIPPED_DIRS
                            and not folder.startswith(".venv") and not (top and folder.startswith("run")))
        for name in sorted(files):
            relative = (Path(directory) / name).relative_to(root).as_posix()
            if not _skipped(relative):
                names.append(relative)
    return names


def _skipped(relative: str) -> bool:
    folders = relative.split("/")[:-1]
    return any(folder in SKIPPED_DIRS for folder in folders)


def read_text(path: Path) -> str | None:
    data = path.read_bytes()
    if b"\0" in data[:8192]:
        return None
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        return None


def line_of(text: str, index: int) -> int:
    return text.count("\n", 0, index) + 1


# --------------------------------------------------------------------------------------------------
# Individual checks


def check_links(root: Path, name: str, text: str, problems: Problems) -> None:
    # Blank out code so examples of link syntax are not links; keep offsets for line numbers.
    masked = FENCE.sub(lambda match: re.sub(r"[^\n]", " ", match.group(0)), text)
    masked = INLINE_CODE.sub(lambda match: " " * len(match.group(0)), masked)
    targets = [(match.start(1), match.group(1)) for pattern in (LINK, REFERENCE, HTML_LINK)
               for match in pattern.finditer(masked)]
    for index, target in sorted(targets):
        if SCHEME.match(target) or target.startswith(("#", "//")):
            continue
        path = unquote(target.split("#", 1)[0].split("?", 1)[0])
        if not path:
            continue
        base = root if path.startswith("/") else (root / name).parent
        resolved = (base / path.lstrip("/")).resolve()
        if not resolved.is_relative_to(root.resolve()):
            problems.add("links", name, f"link {target} points outside the repository", line_of(text, index))
        elif not resolved.exists():
            problems.add("links", name, f"link {target} does not resolve", line_of(text, index))


def check_size(root: Path, name: str, problems: Problems) -> None:
    size = (root / name).stat().st_size
    image = PurePosixPath(name).suffix.lower() in IMAGE_SUFFIXES
    limit = MAX_IMAGE_BYTES if image else MAX_FILE_BYTES
    if size > limit:
        kind = "image" if image else "file"
        problems.add("size", name, f"{kind} has {size} bytes; the limit is {limit} bytes")


def check_forbidden(name: str, problems: Problems) -> None:
    path = PurePosixPath(name)
    folders = path.parts[:-1]
    if path.name in FORBIDDEN_NAMES or path.suffix.lower() in FORBIDDEN_SUFFIXES \
            or FORBIDDEN_PATTERN.search(path.name):
        problems.add("forbidden", name, "generated output, binary package, key or catalog release; keep it out of "
                                        "the repository")
    elif len(folders) >= 3 and folders[0] == "cases" \
            and any(folder == "out" or folder.startswith("run") for folder in folders[2:]):
        problems.add("forbidden", name, "run directory inside a case; keep run outputs out of the repository")


def check_text(name: str, text: str, problems: Problems) -> None:
    for pattern in MACHINE_PATHS:
        for match in pattern.finditer(text):
            problems.add("paths", name, f"absolute machine path {match.group(0)!r}; use a relative or "
                                        "placeholder path", line_of(text, match.start()))
    for label, pattern in SECRETS:
        for match in pattern.finditer(text):
            problems.add("secrets", name, f"looks like a {label}; remove it and revoke it",
                         line_of(text, match.start()))
    for host in RETIRED_HOSTS:
        escaped = re.escape(host).replace(r"\-", "-+")  # shields.io badges write "-" as "--"
        for match in re.finditer(r"(?<!\w)" + escaped + r"(?!\w)", text, re.I):
            problems.add("pins", name, f"retired host {match.group(0)}; use opensci-optics.com",
                         line_of(text, match.start()))


def in_pin_scope(name: str) -> bool:
    return not name.startswith(PIN_EXEMPT)


def check_pins(name: str, text: str, baseline: dict, problems: Problems) -> None:
    engine = (baseline.get("engine") or {}).get("verified_version")
    kit = baseline.get("kit_version")
    for pattern, expected, label in ((ENGINE_PIN, engine, "os-optics"), (KIT_PIN, kit, "os-optics-kit")):
        for match in pattern.finditer(text):
            if expected and match.group(1) != expected:
                problems.add("pins", name, f"{label} pin {match.group(1)} differs from baseline.json {expected}",
                             line_of(text, match.start()))
    for match in RETIRED_PIN.finditer(text):
        problems.add("pins", name, "pin of the former engine distribution name; use os-optics",
                     line_of(text, match.start()))


def check_json(root: Path, name: str, problems: Problems) -> None:
    try:
        json.loads((root / name).read_text(encoding="utf-8"))
    except (UnicodeDecodeError, ValueError) as exc:
        problems.add("json", name, f"invalid JSON: {exc}")


def specifier_clauses(requirement: str) -> frozenset[str]:
    """Order-independent form of a specifier: ``>=0.12,<0.13`` equals ``<0.13, >=0.12``."""
    return frozenset(clause for clause in re.sub(r"\s+", "", requirement).split(",") if clause)


def _version_tuple(text: str) -> tuple[int, ...]:
    match = re.match(r"\d+(?:\.\d+)*", text)
    if not match:
        raise ValueError(f"not a version: {text!r}")
    parts = [int(part) for part in match.group(0).split(".")]
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def satisfies(version: str, requirement: str) -> bool:
    """Evaluate a comma-separated specifier with ==, !=, >=, <=, >, < (release segments only)."""
    try:
        from packaging.specifiers import SpecifierSet
        from packaging.version import Version
        return Version(version) in SpecifierSet(requirement)
    except ImportError:
        pass
    value = _version_tuple(version)
    operators = {">=": lambda a, b: a >= b, "<=": lambda a, b: a <= b, ">": lambda a, b: a > b,
                 "<": lambda a, b: a < b, "==": lambda a, b: a == b, "!=": lambda a, b: a != b}
    for clause in filter(None, (part.strip() for part in requirement.split(","))):
        match = re.fullmatch(r"(>=|<=|==|!=|>|<)\s*(\S+)", clause)
        if not match:
            raise ValueError(f"unsupported specifier {clause!r}")
        if not operators[match.group(1)](value, _version_tuple(match.group(2))):
            return False
    return True


def check_baseline(root: Path, problems: Problems) -> dict:
    name = "baseline.json"
    try:
        baseline = json.loads((root / name).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        problems.add("baseline", name, f"cannot read: {exc}")
        return {}
    if not isinstance(baseline, dict):
        problems.add("baseline", name, "expected an object")
        return {}
    engine: dict = baseline["engine"] if isinstance(baseline.get("engine"), dict) else {}
    catalog: dict = baseline["catalog"] if isinstance(baseline.get("catalog"), dict) else {}
    expected = {"schema": "os-optics-kit.baseline", "schema_version": 1}
    for key, value in expected.items():
        if baseline.get(key) != value:
            problems.add("baseline", name, f"{key} must be {value!r}")
    if engine.get("distribution") != "os-optics":
        problems.add("baseline", name, "engine.distribution must be 'os-optics'")
    if not re.fullmatch(r"20\d\d-\d\d-\d\d\.\d+", str(catalog.get("version"))):
        problems.add("baseline", name, "catalog.version must be a release such as 2026-10-28.1")
    if not re.fullmatch(r"\d+\.\d+", str(catalog.get("schema_version"))):
        problems.add("baseline", name, "catalog.schema_version must be a string such as '3.2'")
    if not re.fullmatch(r"[0-9a-f]{64}", str(catalog.get("sha256"))):
        problems.add("baseline", name, "catalog.sha256 must be 64 lower-case hexadecimal characters")
    python = baseline.get("python")
    if not isinstance(python, list) or not python or not all(
            isinstance(item, str) and re.fullmatch(r"3\.\d+", item) for item in python):
        problems.add("baseline", name, "python must be a non-empty list such as ['3.11', '3.14']")
        python = []

    version_file = root / "tools" / "os_optics_kit" / "_version.py"
    try:
        match = re.search(r"^__version__ = \"([^\"]+)\"", version_file.read_text(encoding="utf-8"), re.M)
        source_version = match.group(1) if match else None
    except OSError:
        source_version = None
    if baseline.get("kit_version") != source_version:
        problems.add("baseline", name, f"kit_version {baseline.get('kit_version')!r} differs from "
                                       f"tools/os_optics_kit/_version.py {source_version!r}")

    if tomllib is None:
        return baseline
    try:
        project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    except (OSError, KeyError, ValueError) as exc:
        problems.add("baseline", "pyproject.toml", f"cannot read [project]: {exc}")
        return baseline
    specifiers = [dependency[len("os-optics"):] for dependency in project.get("dependencies", [])
                  if re.match(r"os-optics(?![\w-])", dependency)]
    requirement = re.sub(r"\s+", "", str(engine.get("requirement")))
    if [specifier_clauses(item) for item in specifiers] != [specifier_clauses(requirement)]:
        problems.add("baseline", name, f"engine.requirement {engine.get('requirement')!r} differs from the "
                                       f"pyproject.toml os-optics dependency {specifiers}")
    verified = engine.get("verified_version")
    try:
        if not isinstance(verified, str) or not satisfies(verified, requirement):
            problems.add("baseline", name, f"engine.verified_version {verified!r} is outside {requirement}")
    except ValueError as exc:
        problems.add("baseline", name, f"engine.requirement: {exc}")
    minimum = re.fullmatch(r">=\s*(3\.\d+)", str(project.get("requires-python", "")).strip())
    classifiers = set(project.get("classifiers", []))
    for item in python:
        if minimum and _version_tuple(item) < _version_tuple(minimum.group(1)):
            problems.add("baseline", name, f"python {item} is older than requires-python {minimum.group(0)}")
        if f"Programming Language :: Python :: {item}" not in classifiers:
            problems.add("baseline", name, f"python {item} has no 'Programming Language :: Python :: {item}' "
                                           "classifier in pyproject.toml")
    return baseline


def check_pairs(names: list[str], problems: Problems) -> None:
    present = set(names)
    for name in names:
        if name.startswith("docs/en/") and name.endswith(".md"):
            partner = "docs/zh-CN/" + name[len("docs/en/"):]
        elif name.startswith("docs/zh-CN/") and name.endswith(".md"):
            partner = "docs/en/" + name[len("docs/zh-CN/"):]
        elif name.endswith(".zh-CN.md"):
            partner = name[:-len(".zh-CN.md")] + ".md"
        elif name == "README.md":
            partner = "README.zh-CN.md"
        else:
            continue
        if partner not in present:
            problems.add("pairs", name, f"missing its language counterpart {partner}")


def run_checks(root: Path) -> dict:
    root = root.resolve()
    problems = Problems()
    names = repository_files(root)
    baseline = check_baseline(root, problems)
    for name in names:
        check_size(root, name, problems)
        check_forbidden(name, problems)
        suffix = PurePosixPath(name).suffix.lower()
        if suffix == ".json":
            check_json(root, name, problems)
        if suffix in IMAGE_SUFFIXES - {".svg"}:
            continue
        text = read_text(root / name)
        if text is None:
            continue
        check_text(name, text, problems)
        if suffix == ".md":
            check_links(root, name, text, problems)
        if in_pin_scope(name):
            check_pins(name, text, baseline, problems)
    check_pairs(names, problems)
    items = sorted(problems.items, key=lambda item: (item["check"], item["path"], item["line"] or 0))
    return {"status": "FAIL" if items else "PASS", "files": len(names), "problems": items}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT, help="Repository root (default: this checkout)")
    args = parser.parse_args(argv)
    result = run_checks(args.root)
    print(json.dumps(result, ensure_ascii=False, separators=(",", ":")))
    if os.environ.get("GITHUB_ACTIONS") == "true":
        for item in result["problems"]:
            location = f"file={item['path']}" + (f",line={item['line']}" if item["line"] else "")
            message = item["message"].replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
            print(f"::error {location},title=check_repo {item['check']}::{message}", file=sys.stderr)
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
